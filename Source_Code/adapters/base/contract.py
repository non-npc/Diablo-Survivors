from typing import Protocol, Callable
from pathlib import Path

class GameAdapter(Protocol):
    def detect(self, path: Path) -> dict: ...
    def inspect(self, path: Path) -> dict: ...
    def enumerate_assets(self, path: Path) -> list[dict]: ...
    def extract(self, path: Path, staging_dir: Path, progress: Callable, cancel: Callable) -> None: ...
    def normalize(self, staging_dir: Path) -> dict: ...
    def suggest_mappings(self, catalog: dict) -> dict: ...
    def validate(self, manifest: dict) -> None: ...
    def get_capabilities(self) -> set[str]: ...
